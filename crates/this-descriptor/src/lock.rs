//! `descriptor/descriptor.lock`: field name -> proto tag, per entity. The types live here so the
//! server applies the lock too (`ModuleDescriptor::compose_locked`); the CLI writes it.
//!
//! The macros never assign a tag (RFC v2 §3.3); this lock does, once, and never moves it:
//! - a new field gets `max(every tag ever used or reserved in the entity, 15) + 1`;
//! - a removed field's tag moves to `reserved` (never reused);
//! - `check` refuses an explicit `proto_tag` that moves a locked field or reuses a tag held
//!   by another field or reserved.
//!
//! Base fields (`id`, `name`, `status`...) keep their framework tags (`base_fields`) and
//! are not locked; `tenant_id` always gets 8.

use std::collections::{BTreeMap, BTreeSet};

use crate::entity::{FIRST_USER_TAG, TENANT_ID, TENANT_ID_TAG};
use crate::framework::codes;
use crate::{ContractError, DescriptorIssue, EntityDesc, ErrorCode, ModuleDescriptor, base_fields};
use serde::{Deserialize, Serialize};

pub const LOCK_FORMAT: u32 = 1;

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct EntityLock {
    #[serde(default)]
    pub fields: BTreeMap<String, u32>,
    /// Tags of removed fields: never handed out again.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub reserved: Vec<u32>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DescriptorLock {
    pub format: u32,
    #[serde(default)]
    pub entities: BTreeMap<String, EntityLock>,
}

impl Default for DescriptorLock {
    fn default() -> Self {
        Self {
            format: LOCK_FORMAT,
            entities: BTreeMap::new(),
        }
    }
}

fn issue(reason: &str, path: String, message: String) -> DescriptorIssue {
    DescriptorIssue {
        code: ErrorCode::new(format!("this.descriptor.{reason}")),
        path,
        message,
    }
}

fn is_base(e: &EntityDesc, field: &str) -> bool {
    base_fields(e.kind).iter().any(|b| b.name == field)
}

impl EntityLock {
    fn used(&self) -> BTreeSet<u32> {
        self.fields
            .values()
            .copied()
            .chain(self.reserved.iter().copied())
            .collect()
    }
}

impl DescriptorLock {
    #[cfg(feature = "yaml")]
    pub fn parse(s: &str) -> Result<Self, ContractError> {
        let lock: Self = serde_yaml::from_str(s).map_err(|e| {
            ContractError::framework(codes::DESCRIPTOR_PARSE)
                .with_param("reason", format!("descriptor.lock is not valid YAML: {e}"))
        })?;
        if lock.format > LOCK_FORMAT {
            return Err(
                ContractError::framework(codes::DESCRIPTOR_PARSE).with_param(
                    "reason",
                    format!(
                        "descriptor.lock format {} is newer than this build ({LOCK_FORMAT})",
                        lock.format
                    ),
                ),
            );
        }
        Ok(lock)
    }

    #[cfg(feature = "yaml")]
    pub fn to_yaml(&self) -> String {
        let mut s = String::from(
            "# Generated by `this descriptor lock`. Commit it: it keeps proto tags stable.\n\
             # A tag is never moved nor reused; removed fields keep theirs in `reserved`.\n",
        );
        s.push_str(&serde_yaml::to_string(self).unwrap_or_default());
        s
    }

    /// Errors only: what `this descriptor check` refuses (exit code 1).
    pub fn check(&self, d: &ModuleDescriptor) -> Vec<DescriptorIssue> {
        let mut out = Vec::new();
        for (entity, el) in &self.entities {
            // A corrupt lock (hand edit / bad merge) is refused too.
            let mut seen: BTreeMap<u32, &str> = BTreeMap::new();
            for (field, tag) in &el.fields {
                if let Some(other) = seen.insert(*tag, field) {
                    out.push(issue(
                        "tag_reused",
                        format!("lock.{entity}.{field}"),
                        format!("tag {tag} held by `{other}` and `{field}` in descriptor.lock"),
                    ));
                }
                if el.reserved.contains(tag) {
                    out.push(issue(
                        "tag_reused",
                        format!("lock.{entity}.{field}"),
                        format!("tag {tag} of `{field}` is reserved (removed field)"),
                    ));
                }
            }
        }
        for e in &d.entities {
            let el = self.entities.get(&e.name);
            let mut explicit: BTreeMap<u32, &str> = BTreeMap::new();
            for f in e.fields.iter().filter(|f| !is_base(e, &f.name)) {
                let Some(tag) = f.proto_tag else { continue };
                let path = format!("entities.{}.fields.{}", e.name, f.name);
                if let Some(other) = explicit.insert(tag, &f.name) {
                    out.push(issue(
                        "tag_reused",
                        path.clone(),
                        format!("tag {tag} also declared on `{other}`"),
                    ));
                }
                let Some(el) = el else { continue };
                match el.fields.get(&f.name) {
                    Some(locked) if *locked != tag => out.push(issue(
                        "tag_moved",
                        path,
                        format!("locked tag {locked}, declared {tag}"),
                    )),
                    Some(_) => {}
                    None => {
                        if el.reserved.contains(&tag) {
                            out.push(issue(
                                "tag_reused",
                                path,
                                format!("tag {tag} belonged to a removed field (reserved)"),
                            ));
                        } else if let Some((other, _)) = el.fields.iter().find(|(_, t)| **t == tag)
                        {
                            out.push(issue(
                                "tag_reused",
                                path,
                                format!("tag {tag} is locked to `{other}`"),
                            ));
                        }
                    }
                }
            }
        }
        out
    }

    /// Warnings: the lock lags behind the descriptor (`this descriptor lock` fixes them).
    pub fn pending(&self, d: &ModuleDescriptor) -> Vec<String> {
        let mut out = Vec::new();
        for e in &d.entities {
            let el = self.entities.get(&e.name);
            for f in e.fields.iter().filter(|f| !is_base(e, &f.name)) {
                if el.is_none_or(|el| !el.fields.contains_key(&f.name)) {
                    out.push(format!("{}.{} has no locked tag", e.name, f.name));
                }
            }
            if let Some(el) = el {
                for name in el.fields.keys() {
                    if e.field(name).is_none() {
                        out.push(format!(
                            "{}.{name} was removed: its tag is not reserved yet",
                            e.name
                        ));
                    }
                }
            }
        }
        out
    }

    /// Bring the lock up to date with `d` (refuse first: call [`Self::check`]). Returns the
    /// changes made, for display.
    pub fn update(&mut self, d: &ModuleDescriptor) -> Vec<String> {
        let mut changes = Vec::new();
        for e in &d.entities {
            let el = self.entities.entry(e.name.clone()).or_default();
            // Removed fields: reserve.
            let gone: Vec<String> = el
                .fields
                .keys()
                .filter(|n| e.field(n).is_none())
                .cloned()
                .collect();
            for name in gone {
                let tag = el.fields.remove(&name).expect("present");
                if !el.reserved.contains(&tag) {
                    el.reserved.push(tag);
                    el.reserved.sort_unstable();
                }
                changes.push(format!("{}.{name}: removed, tag {tag} reserved", e.name));
            }
            // Explicit tags first (they must not be handed out to another field).
            for f in e.fields.iter().filter(|f| !is_base(e, &f.name)) {
                if let (Some(tag), false) = (f.proto_tag, el.fields.contains_key(&f.name)) {
                    el.fields.insert(f.name.clone(), tag);
                    changes.push(format!("{}.{}: tag {tag} (explicit)", e.name, f.name));
                }
            }
            for f in e.fields.iter().filter(|f| !is_base(e, &f.name)) {
                if el.fields.contains_key(&f.name) {
                    continue;
                }
                let tag = if f.name == TENANT_ID {
                    TENANT_ID_TAG
                } else {
                    let used = el.used();
                    let declared = e.fields.iter().filter_map(|f| f.proto_tag);
                    used.into_iter()
                        .chain(declared)
                        .filter(|t| *t >= FIRST_USER_TAG)
                        .max()
                        .map_or(FIRST_USER_TAG, |m| m + 1)
                };
                el.fields.insert(f.name.clone(), tag);
                changes.push(format!("{}.{}: tag {tag}", e.name, f.name));
            }
        }
        changes
    }

    /// Write the locked tags into `d` (fields without an explicit tag) and the reserved tags
    /// into `reserved_tags`.
    pub fn apply(&self, d: &mut ModuleDescriptor) {
        for e in &mut d.entities {
            let Some(el) = self.entities.get(&e.name) else {
                continue;
            };
            for f in &mut e.fields {
                if f.proto_tag.is_none() {
                    f.proto_tag = el.fields.get(&f.name).copied();
                }
            }
            for t in &el.reserved {
                if !e.reserved_tags.contains(t) {
                    e.reserved_tags.push(*t);
                }
            }
            e.reserved_tags.sort_unstable();
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{FieldDesc, FieldType};

    fn module(fields: &[(&str, Option<u32>)]) -> ModuleDescriptor {
        let mut m = ModuleDescriptor::new("shop", "1.0.0");
        let mut e = EntityDesc::new("order");
        e.fields = fields
            .iter()
            .map(|(n, t)| {
                let mut f = FieldDesc::new(*n, FieldType::String);
                f.proto_tag = *t;
                f
            })
            .collect();
        m.entities.push(e);
        m
    }

    #[test]
    fn assigns_from_16_and_never_moves() {
        let mut lock = DescriptorLock::default();
        lock.update(&module(&[("sku", None), ("label", None)]));
        assert_eq!(lock.entities["order"].fields["sku"], 16);
        assert_eq!(lock.entities["order"].fields["label"], 17);
        // Reorder + insert in front: tags do not move.
        lock.update(&module(&[("code", None), ("label", None), ("sku", None)]));
        assert_eq!(lock.entities["order"].fields["sku"], 16);
        assert_eq!(lock.entities["order"].fields["label"], 17);
        assert_eq!(lock.entities["order"].fields["code"], 18);
    }

    #[test]
    fn descriptor_lock_detects_tag_reuse() {
        let mut lock = DescriptorLock::default();
        lock.update(&module(&[("sku", None), ("label", None)]));
        // `label` (17) removed: its tag becomes reserved, never handed out again.
        let changes = lock.update(&module(&[("sku", None)]));
        assert!(changes.iter().any(|c| c.contains("tag 17 reserved")));
        assert_eq!(lock.entities["order"].reserved, vec![17]);
        lock.update(&module(&[("sku", None), ("title", None)]));
        assert_eq!(
            lock.entities["order"].fields["title"], 18,
            "17 is never reused"
        );

        // Explicit tag reusing the reserved one.
        let issues = lock.check(&module(&[
            ("sku", None),
            ("title", None),
            ("note", Some(17)),
        ]));
        assert!(
            issues.iter().any(
                |i| i.code.as_str() == "this.descriptor.tag_reused" && i.path.ends_with("note")
            ),
            "{issues:?}"
        );
        // Explicit tag reusing a live field's tag.
        let issues = lock.check(&module(&[
            ("sku", None),
            ("title", None),
            ("note", Some(16)),
        ]));
        assert!(
            issues.iter().any(|i| i.message.contains("locked to `sku`")),
            "{issues:?}"
        );
        // Explicit tag moving a locked field.
        let issues = lock.check(&module(&[("sku", Some(30)), ("title", None)]));
        assert!(
            issues
                .iter()
                .any(|i| i.code.as_str() == "this.descriptor.tag_moved"),
            "{issues:?}"
        );
        // Corrupt lock: two fields on one tag.
        let mut bad = lock.clone();
        bad.entities
            .get_mut("order")
            .unwrap()
            .fields
            .insert("x".into(), 16);
        assert!(!bad.check(&module(&[("sku", None)])).is_empty());
        // Consistent descriptor: no issue.
        assert!(
            lock.check(&module(&[("sku", None), ("title", None)]))
                .is_empty()
        );
    }

    #[test]
    fn apply_writes_tags_and_reserved() {
        let mut lock = DescriptorLock::default();
        lock.update(&module(&[("sku", None), ("gone", None)]));
        lock.update(&module(&[("sku", None)]));
        let mut d = module(&[("sku", None)]);
        lock.apply(&mut d);
        assert_eq!(d.entities[0].fields[0].proto_tag, Some(16));
        assert_eq!(d.entities[0].reserved_tags, vec![17]);
        let back = DescriptorLock::parse(&lock.to_yaml()).unwrap();
        assert_eq!(back, lock);
    }
}
